import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { youtubeId } from '../functions/api/admin/storefront.js';
const text = file => readFileSync(new URL(file, import.meta.url),'utf8');
assert.equal(youtubeId('https://www.youtube.com/watch?v=dQw4w9WgXcQ'),'dQw4w9WgXcQ');
assert.equal(youtubeId('https://youtu.be/dQw4w9WgXcQ'),'dQw4w9WgXcQ');
for(const value of ['https://evil.com/watch?v=dQw4w9WgXcQ','http://www.youtube.com/watch?v=dQw4w9WgXcQ','javascript:alert(1)','https://youtu.be/INVALID'])assert.equal(youtubeId(value),'');
const pages=['index','landing','product-page','admin','thank-you','privacy','terms','refund','resend'];
for(const page of pages) assert.match(text('../public/'+page+'.html'),/eboora-v45\.css/);
