for(const id of ['homeVideoUrl','storefrontForm','orderList','bulkDeleteBtn','exportOrdersBtn','headlineFont','headlineSize','headlineColor','descriptionFont','descriptionSize','descriptionColor'])assert.ok(admin.includes('id="'+id+'"'),id);
const orders=text('../functions/api/admin/orders.js');
assert.match(orders,/DELETE FROM orders WHERE order_id = \?/);
assert.match(orders,/deleted_orders_audit/);
assert.match(orders,/requireAdmin/);
const catalog=text('../public/catalog.js');
assert.match(catalog,/api\/storefront/);
assert.match(catalog,/youtube-nocookie\.com/);
assert.match(catalog,/searchEmpty/);
